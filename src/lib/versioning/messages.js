/** Shared version command copy for the in-app terminal and Node CLI. */

export function formatVersionReport({ version, build, commit, branch }) {
  return [
    'NodeMind',
    `Version : ${version}`,
    `Build   : ${build}`,
    `Commit  : ${commit}`,
    `Branch  : ${branch}`,
  ];
}

